#!/usr/bin/env python3
"""Snapshot the official RuneScape (RS3) news feed into data/rs3_news.js for the RS3 Update Watch.

Same idea as tools/fetch_news.py (OSRS): the feed sends no CORS header, so a browser on
github.io cannot read it. This script reads each post, finds RS3 Grand Exchange item names
it mentions (names from https://runescape.wiki/w/Module:GEIDs/data.json), and stores each
item's official GE guide price on the last update BEFORE the post's UTC day, taken from the
Weird Gloop exchange history API (the RuneScape Wiki's price backend):
  https://api.weirdgloop.org/exchange/history/rs/last90d?id=<id>
Posts older than ~90 days get no baseline. The page compares the baseline to today's price.

Run:  python3 tools/fetch_rs3_news.py            (writes data/rs3_news.js)
"""
import datetime
import email.utils
import html
import json
import os
import re
import sys
import time
import urllib.request
import xml.etree.ElementTree as ET

sys.path.insert(0, os.path.dirname(__file__))
from wiki import USER_AGENT, get  # noqa: E402
from fetch_news import match_items  # noqa: E402

RSS = "https://secure.runescape.com/m=news/latest_news.rss"
IDS = "https://runescape.wiki/w/Module:GEIDs/data.json?action=raw"
HIST = "https://api.weirdgloop.org/exchange/history/rs/last90d"
OUT = os.path.join(os.path.dirname(__file__), "..", "data", "rs3_news.js")
# RS3 item names that are also ordinary words or community names in news posts
# ("Pink Skirts" is the player-events group, "Spring" is a season). Skipped entirely.
SKIP = {"pink skirt", "spring"}


def post_text(url):
    req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(req, timeout=60) as r:
        s = r.read().decode(r.headers.get_content_charset() or "utf-8", errors="replace")
    i = s.find("c-news-article__content")
    j = s.find("</article>", i)
    s = s[i:j if j > 0 else None]
    s = re.sub(r"<script.*?</script>|<style.*?</style>", " ", s, flags=re.S)
    t = re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", " ", s)))
    k = t.rfind("The RuneScape Team")
    if k > len(t) - 400:
        t = t[:k]
    return t.strip()


def main():
    now = datetime.datetime.now(datetime.timezone.utc)
    req = urllib.request.Request(RSS, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(req, timeout=60) as r:
        root = ET.fromstring(r.read())
    ids = {k: v for k, v in get(IDS).items() if not k.startswith("%")}
    items = [{"id": int(v), "name": k} for k, v in ids.items() if k.lower() not in SKIP]
    hist_cache = {}

    def hist(i):
        if i not in hist_cache:
            try:
                hist_cache[i] = get(HIST, {"id": i}, pause=0.4).get(str(i), [])
            except Exception as e:  # keep going without a baseline
                print("  history failed", i, e)
                hist_cache[i] = []
        return hist_cache[i]

    posts = []
    for it in root.iter("item"):
        title = html.unescape(it.findtext("title", "").strip())
        link = it.findtext("link", "").strip()
        pub = email.utils.parsedate_to_datetime(it.findtext("pubDate"))
        post_day_ms = int(datetime.datetime(pub.year, pub.month, pub.day, tzinfo=datetime.timezone.utc).timestamp()) * 1000
        text, read_error = "", None
        for _ in range(2):
            try:
                text, read_error = post_text(link), None
                break
            except Exception as e:
                read_error = str(e)
                time.sleep(3)
        mentioned = match_items(text, items)
        mentioned.sort(key=lambda m: -m["mentions"])
        mentioned = mentioned[:25]  # keep the snapshot small; most posts name far fewer
        for m in mentioned:
            pts = [p for p in hist(m["id"]) if p["timestamp"] < post_day_ms]
            m["baseline"] = {"ts": pts[-1]["timestamp"] // 1000, "price": pts[-1]["price"], "volume": pts[-1].get("volume")} if pts else None
        posts.append({
            "title": title, "url": link, "date": pub.strftime("%Y-%m-%d"), "category": it.findtext("category", ""),
            "description": html.unescape(it.findtext("description", "").strip()), "chars": len(text),
            "readError": read_error, "items": mentioned,
        })
        print(f"{pub:%Y-%m-%d} {title[:60]:60} items={len(mentioned)}")
    posts.sort(key=lambda p: p["date"], reverse=True)
    data = {"fetchedAt": now.strftime("%Y-%m-%dT%H:%M:%SZ"), "source": RSS, "posts": posts}
    with open(OUT, "w") as f:
        f.write("// Generated by tools/fetch_rs3_news.py at " + data["fetchedAt"] + ". Snapshot, not live.\n")
        f.write("window.RV_RS3_NEWS = " + json.dumps(data, separators=(",", ":"), ensure_ascii=False) + ";\n")


if __name__ == "__main__":
    main()
