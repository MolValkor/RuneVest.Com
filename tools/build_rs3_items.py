#!/usr/bin/env python3
"""Snapshot RuneScape 3 item metadata into data/rs3_items.js for the RS3 page.

Live prices, daily volumes and buy limits are fetched by the browser straight from the
RuneScape Wiki's GE data modules (they send Access-Control-Allow-Origin: *). Item ids,
members flags and High Alchemy values almost never change, so they are saved here once
to keep each page load smaller.

Sources (RuneScape Wiki, updated by the wiki's GE bot from Jagex's official GE database):
  https://runescape.wiki/w/Module:GEIDs/data.json
  https://runescape.wiki/w/Module:GEMembers/data.json
  https://runescape.wiki/w/Module:GEHighAlchs/data.json

Run:  python3 tools/build_rs3_items.py            (writes data/rs3_items.js)
"""
import datetime
import json
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from wiki import get  # noqa: E402

RSW = "https://runescape.wiki/w/Module:{}/data.json?action=raw"
OUT = os.path.join(os.path.dirname(__file__), "..", "data", "rs3_items.js")


def module(name):
    d = get(RSW.format(name))
    return {k: v for k, v in d.items() if not k.startswith("%")}, d.get("%LAST_UPDATE_F%")


def main():
    ids, upd = module("GEIDs")
    mem, _ = module("GEMembers")
    alch, _ = module("GEHighAlchs")
    items = []
    for name, i in sorted(ids.items(), key=lambda kv: kv[0].lower()):
        ha = alch.get(name)
        items.append([name, int(i), 1 if mem.get(name) else 0, ha if isinstance(ha, (int, float)) and ha > 0 else None])
    data = {
        "builtAt": datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d"),
        "wikiDataUpdated": upd,
        "sources": [RSW.format(m).replace("?action=raw", "") for m in ("GEIDs", "GEMembers", "GEHighAlchs")],
        "fields": ["name", "id", "members", "highalch"],
        "items": items,
    }
    with open(OUT, "w") as f:
        f.write("// Generated by tools/build_rs3_items.py on " + data["builtAt"] + ". Item metadata snapshot; prices are live.\n")
        f.write("window.RV_RS3_ITEMS = " + json.dumps(data, separators=(",", ":"), ensure_ascii=False) + ";\n")
    print(len(items), "items;", sum(1 for x in items if x[3]), "with an alch value")


if __name__ == "__main__":
    main()
